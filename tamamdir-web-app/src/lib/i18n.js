export function translate(lang, key, params) {
  const table = translations[lang] ?? translations.tr;
  let text = table[key] ?? translations.tr[key] ?? key;
  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      text = text.replace(new RegExp(`\\{\\{${k}\\}\\}`, "g"), String(v));
    });
  }
  return text;
}

export function tLocation(t, value) {
  return t(`location.${value}`) !== `location.${value}`
    ? t(`location.${value}`)
    : t("location.on_campus");
}

export function tCategory(t, category) {
  if (!category) return "";
  const slug = category.slug ?? category.category_slug;
  const fallback = category.name ?? category.category_name ?? "";
  if (!slug) return fallback;
  const key = `category.${slug}`;
  const translated = t(key);
  return translated !== key ? translated : fallback;
}

export function tPriceUnit(t, unit) {
  const key = `priceUnit.suffix.${unit}`;
  const suffix = t(key);
  return suffix !== key ? suffix : "";
}

export function formatLocalizedPrice(t, price, unit) {
  return `₺${price}${tPriceUnit(t, unit)}`;
}

export function formatLocalizedDelivery(t, days) {
  return days === 1
    ? t("serviceDetail.deliveryOneDay")
    : t("serviceDetail.deliveryDays", { count: days });
}

function normalizeNotifName(raw, t) {
  if (raw === "A user") return t("notifications.aUser");
  if (raw === "A provider") return t("notifications.aProvider");
  return raw;
}

function localizeReviewBody(t, body) {
  if (!body) return body;

  const patterns = [
    {
      re: /^(.+) left (\d+) stars for "(.+)"\.$/,
      key: "notifications.reviewLeftFor",
    },
    {
      re: /^(.+) updated their review to (\d+) stars for "(.+)"\.$/,
      key: "notifications.reviewUpdatedFor",
    },
    {
      re: /^(.+) left (\d+) stars after "(.+)"\.$/,
      key: "notifications.reviewLeftAfter",
    },
    {
      re: /^(.+) updated their review to (\d+) stars after "(.+)"\.$/,
      key: "notifications.reviewUpdatedAfter",
    },
  ];

  for (const { re, key } of patterns) {
    const match = body.match(re);
    if (!match) continue;
    const service =
      match[3] === "your service" || match[3] === "a service"
        ? t("notifications.yourService")
        : match[3];
    return t(key, {
      name: normalizeNotifName(match[1], t),
      rating: match[2],
      service,
    });
  }

  return body;
}

export function formatNotificationText(t, notification, lang) {
  const { type, title, body } = notification;

  if (lang === "en") {
    return { title, body };
  }

  if (type === "message_new") {
    const match = title?.match(/^(.+) sent you a message$/);
    if (match) {
      const name = match[1];
      return {
        title:
          name === "Someone"
            ? t("notifications.messageTitleSomeone")
            : t("notifications.messageTitle", { name }),
        body,
      };
    }
  }

  if (type === "review_new") {
    let localizedTitle = title;
    if (title === "New review received")
      localizedTitle = t("notifications.reviewNewTitle");
    if (title === "Review updated")
      localizedTitle = t("notifications.reviewUpdatedTitle");
    return {
      title: localizedTitle,
      body: localizeReviewBody(t, body),
    };
  }

  return { title, body };
}
